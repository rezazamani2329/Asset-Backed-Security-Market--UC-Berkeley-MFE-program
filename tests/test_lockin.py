"""Checks for mortgage rate lock-in (src/prepayment.py, src/calibration.py, src/lockin.py)."""
import numpy as np
import pandas as pd
import pytest

from src import calibration as cal
from src import prepayment as pp


def toy_pool(coupons):
    n = len(coupons)
    return pd.DataFrame({"Gross Coupon": coupons, "Age": [18] * n,
                         "Current Balance": [100_000.0] * n})


def test_lockin_multiplier():
    assert pp.lockin_multiplier([-1.0, 0.0], 0.2) == pytest.approx([1.0, 1.0])
    assert pp.lockin_multiplier(1.0, pp.LOCKIN_FHFA) == pytest.approx(1 - 0.181, abs=1e-4)
    assert pp.lockin_multiplier(2.0, 0.0) == pytest.approx(1.0)


def test_lockin_off_by_default_keeps_old_results():
    assert pp.PARAMS["lockin"] == 0.0
    loans, rate = toy_pool([6.0, 7.0, 8.0]), np.full(12, 7.0)
    p = {k: v for k, v in pp.PARAMS.items() if k != "lockin"}
    assert pp.calculate_cpr(loans, rate) == pytest.approx(pp.calculate_cpr(loans, rate, p))


def test_lockin_slows_only_locked_in_loans():
    loans, rate = toy_pool([5.5, 8.5]), np.full(12, 7.0)       # gap +1.5 pp, gap -1.5 pp
    base = pp.calculate_cpr(loans, rate)
    locked = pp.calculate_cpr(loans, rate, {**pp.PARAMS, "lockin": 0.5})
    assert (locked[0] < base[0]).all()                           # locked-in loan slows down
    assert locked[1] == pytest.approx(base[1])                   # in-the-money loan unchanged


def test_bucket_model_matches_cpr_formula():
    theta = [pp.PARAMS[k] for k in cal.PREPAY_NAMES]
    inc, age, burn = np.array([-1.5, 0.0, 1.0]), np.array([30.0] * 3), np.zeros(3)
    assert cal.prepay_model_smm(theta, inc, age, burn) == pytest.approx(
        cal.prepay_model_smm(theta + [0.0], inc, age, burn))
    loans, rate = toy_pool(list(7.0 + inc)), np.full(1, 7.0)
    loans["Age"] = 29
    cpr = pp.calculate_cpr(loans, rate, {**pp.PARAMS, "lockin": 0.3})[:, 0]
    assert pp.calculate_smm(cpr) == pytest.approx(cal.prepay_model_smm(theta + [0.3], inc, age, burn))


def synthetic_by_year(lockin=0.4, years=range(2015, 2027), seed=0):
    """Bucket rows whose SMM is generated by the model with a known lock-in strength."""
    rng = np.random.default_rng(seed)
    theta = [pp.PARAMS[k] for k in cal.PREPAY_NAMES] + [lockin]
    rows = []
    for y in years:
        for ib, inc in enumerate(np.arange(-2.5, 2.6, 0.25)):
            for ab, age in enumerate([4.0, 12.0, 30.0, 60.0]):
                w = 1e8
                smm = float(cal.prepay_model_smm(theta, [inc], [age], [0.0])[0]) * (1 + rng.normal(0, 0.02))
                rows.append({"year": y, "inc_b": ib, "age_b": ab, "burn_b": 0, "w": w,
                             "prepaid": smm * w, "wi": w * inc, "wa": w * age, "wb": 0.0, "n": 1000})
    return pd.DataFrame(rows)


def test_fit_recovers_lockin():
    b = cal.by_year_to_buckets(synthetic_by_year(0.4), range(2015, 2027))
    fit = cal.fit_prepay(b, lockin=True)
    assert fit["lockin"] == pytest.approx(0.4, abs=0.1)
    base = {k: pp.PARAMS[k] for k in cal.PREPAY_NAMES}
    assert cal.fit_lockin_only(b, base) == pytest.approx(0.4, abs=0.05)


def test_out_of_time_lockin_beats_no_lockin():
    res = cal.out_of_time_prepay(synthetic_by_year(0.4), range(2015, 2022), range(2022, 2027))
    by_year = res["by_year"]
    assert list(by_year.index) == list(range(2022, 2027))
    assert (by_year["rmse_smm_lock-in"] <= by_year["rmse_smm_no lock-in"] + 1e-9).all()
